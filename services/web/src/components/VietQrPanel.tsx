import { CopyButton } from "@/components/CopyButton";
import { formatVnd } from "@/lib/format";
import type { VietQrPayment } from "@/lib/payment";

/** The transfer instructions of a payable order (from paymentCache), each field copyable. */
export function VietQrPanel({ payment }: { payment: VietQrPayment }) {
  const amount = formatVnd(payment.amount);
  const rows: { label: string; value: string; copy?: string }[] = [
    { label: "Ngân hàng", value: payment.bank_code, copy: payment.bank_code },
    { label: "Số tài khoản", value: payment.account_number, copy: payment.account_number },
    { label: "Chủ tài khoản", value: payment.account_name, copy: payment.account_name },
    // The amount copies as plain digits, the form a banking app accepts.
    { label: "Số tiền", value: amount, copy: payment.amount.replace(/\.\d+$/, "") },
    { label: "Nội dung", value: payment.content, copy: payment.content },
  ];
  return (
    <section className="qr-panel" aria-labelledby="qr-title">
      <h2 id="qr-title" className="h-display">
        Quét mã để chuyển khoản
      </h2>
      {/* The VietQR image is generated by the bank-QR service for these exact details. */}
      {/* eslint-disable-next-line @next/next/no-img-element */}
      <img className="qr" src={payment.qr_image_url} alt="Mã VietQR" width={240} height={240} referrerPolicy="no-referrer" />
      <dl className="qr-fields">
        {rows.map((r) => (
          <div key={r.label} className="qr-row">
            <dt>{r.label}</dt>
            <dd>
              <b>{r.value}</b>
              {r.copy && <CopyButton value={r.copy} label={r.label.toLowerCase()} />}
            </dd>
          </div>
        ))}
      </dl>
      <p className="fine">
        Giữ nguyên nội dung chuyển khoản. Lượt được cộng ngay khi ngân hàng báo về, thường dưới 1 phút.
      </p>
    </section>
  );
}
