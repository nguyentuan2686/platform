"""Writes services/astro-chart-svc/tests/fixtures/swe-reference.json (house cusps and lunar node).

Swiss Ephemeris (pyswisseph) runs only in this throwaway container; it is never part of
services/, Cargo.lock or an image. Deterministic: fixed case list, no clock, no randomness.
"""
import json
import os
import swisseph as swe

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                   "../../../../services/astro-chart-svc/tests/fixtures/swe-reference.json")
FLAGS = swe.FLG_MOSEPH
LATS = [-45.0, -33.87, 0.0, 10.82, 21.03, 35.68, 51.51, 60.17, 66.0]
LONS = [105.8542, -74.0, 0.0, 151.2, -122.4, 139.69, 18.4, -58.4]


def r7(x):
    return round(float(x), 7)


def cusps_of(jd, lat, lon, system):
    cusps, ascmc = swe.houses_ex(jd, lat, lon, system, FLAGS)
    return [r7(c) for c in cusps][:12], ascmc


def case(utc_tuple, lat, lon, placidus_ok=True):
    y, mo, d, h, mi = utc_tuple
    jd = swe.julday(y, mo, d, h + mi / 60.0)
    eps = swe.calc_ut(jd, swe.ECL_NUT, FLAGS)[0][0]
    placidus = None
    if placidus_ok and abs(lat) < 90.0 - eps:
        try:
            c, am = cusps_of(jd, lat, lon, b"P")
            placidus = {"asc": r7(am[0]), "mc": r7(am[1]), "cusps": c}
        except swe.Error:
            placidus = None
    ws, _ = cusps_of(jd, lat, lon, b"W")
    eq, _ = cusps_of(jd, lat, lon, b"E")
    return {
        "utc": f"{y:04d}-{mo:02d}-{d:02d}T{h:02d}:{mi:02d}:00Z",
        "lat": lat, "lon": lon,
        "placidus": placidus,
        "wholeSign": {"cusps": ws},
        "equal": {"cusps": eq},
        "trueNode": r7(swe.calc_ut(jd, swe.TRUE_NODE, FLAGS)[0][0]),
        "meanNode": r7(swe.calc_ut(jd, swe.MEAN_NODE, FLAGS)[0][0]),
    }


cases = []
for i in range(40):  # dates spread over 1900-2100
    t = (1900 + i * 5 + (i % 5), (i * 5) % 12 + 1, (i * 7) % 28 + 1, (i * 11) % 24, (i * 13) % 60)
    cases.append(case(t, LATS[i % 9], LONS[i % 8]))
assert all(c["placidus"] is not None for c in cases)
polar = case((1990, 7, 15, 7, 30), 69.65, 18.96)  # Tromso: Placidus undefined
assert polar["placidus"] is None
cases.append(polar)

doc = {"source": f"pyswisseph {swe.__version__}, Moshier, generated by tools/fixtures/astro/swe", "cases": cases}
with open(OUT, "w", encoding="utf-8", newline="\n") as f:
    f.write('{"source":' + json.dumps(doc["source"]) + ',"cases":[\n')
    f.write(",\n".join(json.dumps(c, separators=(",", ":")) for c in cases))
    f.write("\n]}\n")
print(f"swe-reference.json: {len(cases)} cases, pyswisseph {swe.__version__}")
